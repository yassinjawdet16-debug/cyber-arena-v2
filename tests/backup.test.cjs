const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const stations=html.match(/const DEFAULT_STATIONS\s*=\s*(\[[\s\S]*?\]);/);
const validator=html.match(/function validateArenaBackup\(x\)\{[^\n]+\}/);
assert.ok(stations&&validator,'Backup validator and stations must exist');
const ctx={};vm.runInNewContext(stations[0]+'\n'+validator[0],ctx);
const good={stations:JSON.parse(JSON.stringify(vm.runInNewContext(stations[0]+';DEFAULT_STATIONS'))),settings:{pin:'test'},sessions:[],sales:[],bills:[],adjustments:[],active:{},archives:{}};
assert.equal(ctx.validateArenaBackup(good),true);
assert.equal(ctx.validateArenaBackup({...good,stations:good.stations.slice(1)}),false);
assert.equal(ctx.validateArenaBackup({...good,bills:null}),false);
assert.equal(ctx.validateArenaBackup({...good,archives:{yesterday:null}}),false);
assert.equal(ctx.validateArenaBackup({...good,stations:good.stations.map((s,i)=>i? s:{...s,rate:1})}),false);
assert.equal(ctx.validateArenaBackup({...good,sales:[{qty:2,unitPrice:500,total:900}]}),false,'Reject mismatched sale totals');
assert.equal(ctx.validateArenaBackup({...good,sales:[{qty:2,unitPrice:500,total:1000}]}),true,'Accept valid sale totals');
assert.equal(ctx.validateArenaBackup({...good,bills:[{amount:-250}]}),false,'Reject negative bill amount');
assert.equal(ctx.validateArenaBackup({...good,adjustments:[{amount:Infinity}]}),false,'Reject invalid cash movement');
assert.equal(ctx.validateArenaBackup({...good,sessions:[{charge:-250,endedAt:12345}]}),false,'Reject negative session charge');
assert.equal(ctx.validateArenaBackup({...good,sessions:[{charge:500,endedAt:Infinity}]}),false,'Reject invalid session timestamp');
assert.equal(ctx.validateArenaBackup({...good,archives:{'2026-10-22':[{charge:-100,endedAt:12345}]}}),false,'Reject corrupted archived income');
assert.equal(ctx.validateArenaBackup({...good,sessions:[{charge:500,endedAt:12345}]}),true,'Accept valid completed session');
console.log('PASS backup structure validation and rejection cases');
